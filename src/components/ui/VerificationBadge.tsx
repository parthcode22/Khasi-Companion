import React, { useState } from 'react';
import { ShieldCheck, Award, Clock, Cpu, AlertTriangle, Info } from 'lucide-react';
import type { VerificationStatus } from '../../types/khasi';

export interface VerificationBadgeProps {
  status: VerificationStatus | string;
  size?: 'xs' | 'sm' | 'md' | 'lg';
  showIcon?: boolean;
  showTooltip?: boolean;
  className?: string;
  labelOverride?: string;
}

interface StatusConfig {
  label: string;
  shortLabel: string;
  description: string;
  icon: React.ComponentType<{ className?: string }>;
  containerClass: string;
  iconClass: string;
  textClass: string;
  indicatorClass: string;
}

const STATUS_CONFIGS: Record<VerificationStatus, StatusConfig> = {
  verified_official: {
    label: 'Official Sourced Record',
    shortLabel: 'Official',
    description: 'Directly authenticated with Directorate of Tourism, Meghalaya Police ERSS 112, or Dorbar Shnong official records.',
    icon: ShieldCheck,
    containerClass: 'bg-[#FAF9F6] border-[#B22222]/40 hover:border-[#B22222] shadow-[0_2px_8px_rgba(178,34,34,0.08)]',
    iconClass: 'text-[#B22222]',
    textClass: 'text-[#B22222]',
    indicatorClass: 'bg-[#B22222]',
  },
  verified_native_speaker: {
    label: 'Native Speaker Verified',
    shortLabel: 'Native Verified',
    description: 'Pronunciation, honorifics, and dialect verified by native Khasi elders and cultural custodians.',
    icon: Award,
    containerClass: 'bg-[#DAA520]/10 border-[#DAA520]/70 hover:border-[#DAA520] shadow-[0_2px_8px_rgba(218,165,32,0.12)]',
    iconClass: 'text-[#B8860B]',
    textClass: 'text-[#8B6508]',
    indicatorClass: 'bg-[#DAA520]',
  },
  needs_review: {
    label: 'Pending Native Review',
    shortLabel: 'Needs Review',
    description: 'Sourced phrase awaiting community elder sign-off. Khasi text is intentionally withheld until authenticated.',
    icon: Clock,
    containerClass: 'bg-[#E97451]/10 border-[#E97451]/50 hover:border-[#E97451] shadow-[0_2px_8px_rgba(233,116,81,0.1)]',
    iconClass: 'text-[#E97451]',
    textClass: 'text-[#C85A38]',
    indicatorClass: 'bg-[#E97451]',
  },
  unverified: {
    label: 'Unverified Machine Translation',
    shortLabel: 'Machine / Unverified',
    description: 'Raw neural inference generated by Model A. Not yet certified by native speakers or official registry.',
    icon: Cpu,
    containerClass: 'bg-[#1A1A1A]/5 border-[#1A1A1A]/20 hover:border-[#1A1A1A]/40 text-[#4A4A4A]',
    iconClass: 'text-[#4A4A4A]',
    textClass: 'text-[#4A4A4A]',
    indicatorClass: 'bg-[#767676]',
  },
  outdated: {
    label: 'Review Needed (Outdated)',
    shortLabel: 'Outdated',
    description: 'Information may have changed since last audit. Subject to re-verification by local authorities.',
    icon: AlertTriangle,
    containerClass: 'bg-amber-50 border-amber-300 hover:border-amber-400 text-amber-900',
    iconClass: 'text-amber-700',
    textClass: 'text-amber-800',
    indicatorClass: 'bg-amber-500',
  },
};

const SIZE_CONFIGS = {
  xs: {
    padding: 'px-2 py-0.5',
    text: 'text-[10px]',
    iconSize: 'w-3 h-3',
    dotSize: 'w-1.5 h-1.5',
  },
  sm: {
    padding: 'px-2.5 py-1',
    text: 'text-xs',
    iconSize: 'w-3.5 h-3.5',
    dotSize: 'w-2 h-2',
  },
  md: {
    padding: 'px-3 py-1.5',
    text: 'text-xs',
    iconSize: 'w-4 h-4',
    dotSize: 'w-2 h-2',
  },
  lg: {
    padding: 'px-4 py-2',
    text: 'text-sm font-semibold',
    iconSize: 'w-4.5 h-4.5',
    dotSize: 'w-2.5 h-2.5',
  },
};

export const VerificationBadge: React.FC<VerificationBadgeProps> = ({
  status,
  size = 'sm',
  showIcon = true,
  showTooltip = true,
  className = '',
  labelOverride,
}) => {
  const [isTooltipVisible, setIsTooltipVisible] = useState(false);

  // Normalize status string or fallback to unverified
  const normalizedStatus = (
    Object.keys(STATUS_CONFIGS).includes(status) ? status : 'unverified'
  ) as VerificationStatus;

  const config = STATUS_CONFIGS[normalizedStatus];
  const sizeConfig = SIZE_CONFIGS[size];
  const IconComponent = config.icon;
  const displayLabel = labelOverride || (size === 'xs' ? config.shortLabel : config.label);

  return (
    <div
      className={`relative inline-flex items-center group ${className}`}
      onMouseEnter={() => setIsTooltipVisible(true)}
      onMouseLeave={() => setIsTooltipVisible(false)}
      onFocus={() => setIsTooltipVisible(true)}
      onBlur={() => setIsTooltipVisible(false)}
      tabIndex={showTooltip ? 0 : undefined}
      aria-label={`${config.label}: ${config.description}`}
    >
      <span
        className={`inline-flex items-center gap-1.5 rounded-full border transition-all duration-150 select-none ${sizeConfig.padding} ${sizeConfig.text} ${config.containerClass}`}
      >
        <span
          className={`rounded-full shrink-0 ${sizeConfig.dotSize} ${config.indicatorClass}`}
          aria-hidden="true"
        />
        {showIcon && (
          <IconComponent
            className={`shrink-0 ${sizeConfig.iconSize} ${config.iconClass}`}
            aria-hidden="true"
          />
        )}
        <span className={`font-medium tracking-tight ${config.textClass}`}>
          {displayLabel}
        </span>
        {showTooltip && (
          <Info
            className={`w-3 h-3 opacity-40 group-hover:opacity-80 transition-opacity ml-0.5 ${config.iconClass}`}
            aria-hidden="true"
          />
        )}
      </span>

      {/* Floating Info Tooltip */}
      {showTooltip && isTooltipVisible && (
        <div
          role="tooltip"
          className="absolute z-50 bottom-full left-1/2 -translate-x-1/2 mb-2 w-64 p-3 bg-[#1A1A1A] text-[#FAF9F6] text-[11px] rounded-xl shadow-xl border border-[#DAA520]/40 pointer-events-none animate-fadeIn transition-opacity font-sans"
        >
          <div className="flex items-center gap-1.5 font-semibold text-[#DAA520] mb-1">
            <IconComponent className="w-3.5 h-3.5 text-[#DAA520]" />
            <span>{config.label}</span>
          </div>
          <p className="text-[#FAF9F6]/85 leading-relaxed font-normal">
            {config.description}
          </p>
          <div className="mt-2 pt-1.5 border-t border-[#FAF9F6]/15 text-[10px] text-[#FAF9F6]/60 flex items-center justify-between">
            <span>Fact-Separation Firewall</span>
            <span className="text-[#DAA520] font-mono">Verified</span>
          </div>
          {/* Arrow */}
          <div className="absolute top-full left-1/2 -translate-x-1/2 -mt-1 border-4 border-transparent border-t-[#1A1A1A]" />
        </div>
      )}
    </div>
  );
};

export default VerificationBadge;
